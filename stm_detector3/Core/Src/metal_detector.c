/* Completed-frame ring: last-JEOS ISR writes (the ADC IRQs share priority
 * 3, so writes never nest), app task reads. Free-running indices, same
 * discipline as gps.c's echo ring. A full ring drops the frame — the
 * tick gap tells the host — and counts the overrun (debugger-visible). */
#define MD_FRAME_RING 32U               /* power of two */
static md_frame_t md_frame_ring[MD_FRAME_RING];
static volatile uint32_t md_frame_head = 0U;  /* ISR writes  */
static volatile uint32_t md_frame_tail = 0U;  /* task writes */
volatile uint32_t md_frame_overruns = 0U;

uint8_t md_frame_pop(md_frame_t *out)
{
    uint32_t tail = md_frame_tail;
    if (tail == md_frame_head)
        return 0U;
    *out = md_frame_ring[tail & (MD_FRAME_RING - 1U)];
    md_frame_tail = tail + 1U;
    return 1U;
}

/* Cycles per GPS period — the g/b console keys step through the divisor
 * list below; persisted with the settings (packed into the rx_window
 * record word). The pacer reads this per arm, so a change takes effect
 * within one fix interval. */
volatile uint8_t md_samples_per_period = MD_SAMPLES_PER_GPS_PERIOD;

static const uint8_t md_rate_steps[] = { 1U, 2U, 5U, 10U, 25U };
#define MD_RATE_STEPS (sizeof(md_rate_steps) / sizeof(md_rate_steps[0]))

static uint8_t md_rate_valid(uint32_t sp)
{
    for (uint32_t i = 0U; i < MD_RATE_STEPS; i++)
        if (md_rate_steps[i] == sp)
            return 1U;
    return 0U;
}

static uint32_t md_sample_rate_hz(void)
{
    return 1000U * md_samples_per_period / MD_GPS_PERIOD_MS;
}

/* Sample interval in TIM7 ticks (0.1 ms): 20 ticks at 500 Hz .. 500 at 20. */
static uint32_t md_interval_ticks(void)
{
    return MD_GPS_PERIOD_MS * MD_PACE_TICKS_PER_MS / md_samples_per_period;
}

/* Recompute the raster slot period from the worst channel's timeline and
 * check the sweep fits the sample interval. Applies (md_slot_ticks) and
 * returns 1, or changes nothing and returns 0. The slot period stretches
 * past the 200 µs floor when a channel's tx+bl+rx grows too long for it
 * OR when the requested pulse spacing (md_pulse_ticks) is slower — always
 * reported (info line / rastercfg echo), never truncated. */
static uint8_t md_raster_apply(void)
{
    uint32_t worst = 0U;
    for (uint32_t k = 0U; k < 8U; k++) {
        uint32_t t = (uint32_t)md_ch_tx_us[k] + md_ch_bl_us[k] + md_ch_rx_us[k];
        if (t > worst) worst = t;
    }
    uint32_t ticks = (worst + MD_SLOT_ADC_US + MD_SLOT_MARGIN_US + 99U) / 100U;
    if (ticks < MD_SLOT_TICKS_MIN)
        ticks = MD_SLOT_TICKS_MIN;
    if (ticks < md_pulse_ticks)
        ticks = md_pulse_ticks;
    md_slot_want = (uint8_t)ticks;   /* remembered even when refused: the
                                        raster-limit warn prints the value
                                        that failed the fit, not the one
                                        still applied (self-contradictory
                                        numbers otherwise) */
    if (8U * ticks > md_interval_ticks())
        return 0U;
    md_slot_ticks = (uint8_t)ticks;
    return 1U;
}

/* Would the current slot period still fit at sp samples per GPS period? */
static uint8_t md_raster_rate_ok(uint32_t sp)
{
    return !md_raster
        || 8U * (uint32_t)md_slot_ticks
           <= MD_GPS_PERIOD_MS * MD_PACE_TICKS_PER_MS / sp;
}

/* Seed the per-channel table from the shared globals (legacy settings
 * records, defaults, CLEAR). */
static void md_table_seed(void)
{
    for (uint32_t k = 0U; k < 8U; k++) {
        md_ch_tx_us[k] = (uint8_t)md_tx_pulse_us;
        md_ch_bl_us[k] = (uint8_t)md_blanking_us;
        md_ch_rx_us[k] = (uint8_t)md_rx_window_us;
    }
}

static void md_table_copy(uint8_t *dst, const volatile uint8_t *src)
{
    for (uint32_t k = 0U; k < 8U; k++)
        dst[k] = src[k];
}

static void md_table_restore(volatile uint8_t *dst, const uint8_t *src)
{
    for (uint32_t k = 0U; k < 8U; k++)
        dst[k] = src[k];
}

/* Nudge the selected channel(s) of one table field by delta, clamped.
 * Returns 1 if any value changed. */
static int md_table_adj(volatile uint8_t *tab, int delta,
                        uint32_t lo, uint32_t hi)
{
    int any = 0;
    uint32_t k0 = (md_sel_ch == MD_SEL_ALL) ? 0U : md_sel_ch;
    uint32_t k1 = (md_sel_ch == MD_SEL_ALL) ? 7U : md_sel_ch;
    for (uint32_t k = k0; k <= k1; k++) {
        int32_t v = (int32_t)tab[k] + delta;
        if (v < (int32_t)lo) v = (int32_t)lo;
        if (v > (int32_t)hi) v = (int32_t)hi;
        if ((uint8_t)v != tab[k]) { tab[k] = (uint8_t)v; any = 1; }
    }
    return any;
}

typedef struct {
    ADC_TypeDef *adc;
    uint8_t      ch1, ch2;  /* injected sequence: ch1 then ch2 (both 1..9)  */
    uint8_t      idx;       /* md_adc[idx] = ch1 result, [idx+1] = ch2      */
} md_adc_pair_t;

static const md_adc_pair_t md_adc_pairs[4] = {
    { ADC1, 1, 2, 0 },      /* PA0,  PA1  */
    { ADC2, 3, 4, 2 },      /* PA6,  PA7  */
    { ADC3, 1, 5, 4 },      /* PB1,  PB13 */
    { ADC4, 3, 4, 6 },      /* PB12, PB14 */
};

/* 0x0F = idle/complete; md_adc_kick clears it, each JEOS sets its bit.
 * The three ADC IRQs share priority 3, so they never preempt each other
 * and the read-modify-write below is race-free. */
static volatile uint8_t md_adc_done_mask = 0x0FU;

#define MD_ADC_SMP_47CYC5  4U   /* SMPR code: 47.5 ADC clocks @ 42.5 MHz    */

/* Calibrate, set sampling times, load the injected sequences, enable, and
 * unmask JEOS. CubeMX's HAL_ADC_Init already ran (regulator up, JQDIS=1,
 * independent mode); this owns the rest, per the module's override pattern. */
static void md_adc_init(void)
{
    ADC_HandleTypeDef *hs[4] = { &hadc1, &hadc2, &hadc3, &hadc4 };

    for (uint32_t i = 0; i < 4U; i++) {
        const md_adc_pair_t *p = &md_adc_pairs[i];

        HAL_ADCEx_Calibration_Start(hs[i], ADC_SINGLE_ENDED);

        /* Injected 16x oversampling, no shift: each JDR is the hardware
         * SUM of 16 conversions — max 16*4095 = 65520, so the values
         * still fit uint16_t end-to-end (md_adc[], CSV, daemon). ~2 more
         * effective bits for a ~16x longer sequence (~45 us/pair), which
         * the 2 ms-and-up sample cadence has to spare. Full-register write also
         * evicts anything a debugger poke left behind (JADSTART is 0). */
        p->adc->CFGR2 = ADC_CFGR2_JOVSE | (3U << ADC_CFGR2_OVSR_Pos);

        uint32_t smpr = p->adc->SMPR1;      /* both channels are 1..9        */
        smpr &= ~((7U << (3U * p->ch1)) | (7U << (3U * p->ch2)));
        smpr |=  (MD_ADC_SMP_47CYC5 << (3U * p->ch1))
               | (MD_ADC_SMP_47CYC5 << (3U * p->ch2));
        p->adc->SMPR1 = smpr;

        /* JL=1 → 2 conversions; JEXTEN=0 → software start (JADSTART) */
        p->adc->JSQR = ADC_JSQR_JL_0
                     | ((uint32_t)p->ch1 << ADC_JSQR_JSQ1_Pos)
                     | ((uint32_t)p->ch2 << ADC_JSQR_JSQ2_Pos);

        p->adc->ISR = ADC_ISR_ADRDY;
        p->adc->CR |= ADC_CR_ADEN;
        while (!(p->adc->ISR & ADC_ISR_ADRDY)) {}
        p->adc->ISR = ADC_ISR_JEOS | ADC_ISR_JEOC;
        p->adc->IER |= ADC_IER_JEOSIE;
    }

    /* Below the timers (2), above the GPS UART (6). Handlers live in
     * stm32g4xx_it.c USER CODE 1 — CubeMX does not generate them. */
    HAL_NVIC_SetPriority(ADC1_2_IRQn, 3, 0);
    HAL_NVIC_EnableIRQ(ADC1_2_IRQn);
    HAL_NVIC_SetPriority(ADC3_IRQn, 3, 0);
    HAL_NVIC_EnableIRQ(ADC3_IRQn);
    HAL_NVIC_SetPriority(ADC4_IRQn, 3, 0);
    HAL_NVIC_EnableIRQ(ADC4_IRQn);
}

/* Hot path: start all four injected sequences. The pair JSQRs are
 * rewritten on every kick (legal: JADSTART is clear between cycles, and
 * the previous cycle is complete by the overlap guard) — raster slots
 * reprogram JSQR to a single conversion, so the simultaneous path is
 * self-healing after any mode toggle instead of needing a restore step. */
static inline void md_adc_kick(void)
{
    md_kick_raster = 0U;
    md_adc_done_mask = 0U;
    for (uint32_t i = 0U; i < 4U; i++) {
        const md_adc_pair_t *p = &md_adc_pairs[i];
        p->adc->JSQR = ADC_JSQR_JL_0
                     | ((uint32_t)p->ch1 << ADC_JSQR_JSQ1_Pos)
                     | ((uint32_t)p->ch2 << ADC_JSQR_JSQ2_Pos);
        p->adc->CR |= ADC_CR_JADSTART;
    }
}

/* Raster hot path: convert ONLY the slot's channel (JL=0, one conversion,
 * ~23 µs at 16x oversampling) on the ADC that owns it. The pair-mate
 * belongs to the parked set — its integrator was never reset or gated
 * this slot, so there is nothing meaningful to read. */
static inline void md_adc_kick_one(void)
{
    uint32_t k = md_slot_ch;
    const md_adc_pair_t *p = &md_adc_pairs[k >> 1];
    md_kick_raster = 1U;
    md_adc_done_mask = (uint8_t)(0x0FU & ~(1U << (k >> 1)));
    p->adc->JSQR = (uint32_t)((k & 1U) ? p->ch2 : p->ch1) << ADC_JSQR_JSQ1_Pos;
    p->adc->CR |= ADC_CR_JADSTART;
}

/* ---------------------------------------------------------------------------
 * System status (1 Hz CSV append): PA8 rail monitor + die temperature on
 * ADC5 — intentionally an ADC the detector circuit doesn't use. Blocking
 * injected read of 3 channels (~18 us at 247.5-cycle sampling, task
 * context only). PA8 sees its rail through a 10k series / 1k-to-ground
 * divider (x11). VREFINT is read alongside so VDDA is computed from the
 * factory-calibrated bandgap each time; temp uses TS_CAL1/TS_CAL2 (30 C /
 * 130 C points, both calibrated at VREF+ = 3.0 V).
 * ------------------------------------------------------------------------- */
#define MD_STATUS_DIVIDER    11.0f    /* (10k + 1k) / 1k                    */
#define MD_ADC5_CH_VIN       1U       /* PA8 = ADC5_IN1                     */
#define MD_ADC5_CH_TEMP      4U       /* temp sensor = ADC5_IN4             */
#define MD_ADC5_CH_VREFINT   18U      /* VREFINT = ADC5_IN18                */
#define MD_ADC_SMP_247CYC5   6U       /* temp sensor needs >= 5 us sampling */

static void md_status_init(void)
{
    HAL_ADCEx_Calibration_Start(&hadc5, ADC_SINGLE_ENDED);

    /* Route VREFINT to IN18 (VSENSESEL for the temp sensor was already set
     * by the CubeMX channel config). */
    ADC345_COMMON->CCR |= ADC_CCR_VREFEN;

    ADC5->SMPR1 = (ADC5->SMPR1
                   & ~((7U << (3U * MD_ADC5_CH_VIN))
                     | (7U << (3U * MD_ADC5_CH_TEMP))))
                  | (MD_ADC_SMP_247CYC5 << (3U * MD_ADC5_CH_VIN))
                  | (MD_ADC_SMP_247CYC5 << (3U * MD_ADC5_CH_TEMP));
    ADC5->SMPR2 = (ADC5->SMPR2
                   & ~(7U << (3U * (MD_ADC5_CH_VREFINT - 10U))))
                  | (MD_ADC_SMP_247CYC5 << (3U * (MD_ADC5_CH_VREFINT - 10U)));

    /* Injected sequence: VIN, TEMP, VREFINT; software-triggered (JEXTEN=0) */
    ADC5->JSQR = ADC_JSQR_JL_1                          /* JL=2 -> 3 convs  */
               | (MD_ADC5_CH_VIN     << ADC_JSQR_JSQ1_Pos)
               | (MD_ADC5_CH_TEMP    << ADC_JSQR_JSQ2_Pos)
               | (MD_ADC5_CH_VREFINT << ADC_JSQR_JSQ3_Pos);

    ADC5->ISR = ADC_ISR_ADRDY;
    ADC5->CR |= ADC_CR_ADEN;
    while (!(ADC5->ISR & ADC_ISR_ADRDY)) {}
}

void md_status_read(float *vin_volts, float *temp_c)
{
    ADC5->ISR = ADC_ISR_JEOS | ADC_ISR_JEOC;
    ADC5->CR |= ADC_CR_JADSTART;
    while (!(ADC5->ISR & ADC_ISR_JEOS)) {}              /* ~18 us           */
    uint32_t raw_vin  = ADC5->JDR1;
    uint32_t raw_temp = ADC5->JDR2;
    uint32_t raw_vref = ADC5->JDR3;
    ADC5->ISR = ADC_ISR_JEOS | ADC_ISR_JEOC;

    if (raw_vref == 0U)                                 /* broken bandgap   */
        raw_vref = 1U;

    /* Actual VDDA from the bandgap: cal value was taken at 3.0 V */
    float vdda = 3.0f * (float)(*VREFINT_CAL_ADDR) / (float)raw_vref;

    /* Scale the temp reading into the 3.0 V calibration domain, then
     * interpolate between the two factory points. */
    float ts = (float)raw_temp * vdda / 3.0f;
    *temp_c = 30.0f + (130.0f - 30.0f)
              * (ts - (float)(*TEMPSENSOR_CAL1_ADDR))
              / ((float)(*TEMPSENSOR_CAL2_ADDR) - (float)(*TEMPSENSOR_CAL1_ADDR));

    *vin_volts = (float)raw_vin / 4095.0f * vdda * MD_STATUS_DIVIDER;
}

/* ---------------------------------------------------------------------------
 * Flash settings storage — append-log in the last 4 KB page (page 31 at
 * 0x0801F000; the linker FLASH region is shrunk to 124K so the app image
 * can never grow into it). Each save appends one 32-byte record; the page
 * is erased only when all 128 slots are used, so the ~22 ms single-bank
 * erase stall (CPU can't fetch from flash during erase) almost never
 * happens. Loading takes the last valid record; a blank page = defaults.
 * ------------------------------------------------------------------------- */
#define MD_SETTINGS_PAGE_ADDR  0x0801F000UL
#define MD_SETTINGS_PAGE       31U            /* 4 KB pages, DBANK=0        */
#define MD_SETTINGS_MAGIC      0x3354444DUL   /* 'MDT3' — legacy 32 B       */
#define MD_SETTINGS_MAGIC4     0x3454444DUL   /* 'MDT4' — 64 B, raster      */

typedef struct __attribute__((aligned(8))) {
    uint32_t magic;
    uint32_t blanking_us;          /* bits 23:0 blanking; bits 31:24 held
                                      the retired fire mode — ignored on
                                      load, written 0 (both sets always
                                      fire now)                           */
    uint32_t rx_window_us;         /* bits 7:0 rx window (<= 50); bits
                                      15:8 samples per GPS period (0 =
                                      pre-rate record -> default applies) */
    uint32_t coil_spacing_mm;      /* 0xFFFFFFFF = pre-geometry record     */
    int32_t  coil_offset_fore_mm;  /* array center vs antenna, + forward   */
    int32_t  coil_offset_right_mm; /* + starboard                          */
    uint32_t tx_pulse_us;          /* was the spare word: 0xFFFFFFFF in
                                      older records -> default applies     */
    uint32_t check;                /* ~(XOR of the 7 words above)          */
} md_settings_rec_t;               /* 32 bytes = 4 flash doublewords       */

/* v4 record: the MDT3 layout plus the raster mode flag and the per-channel
 * timing table. Saves always write this; loads accept either magic (the
 * newest valid record of any vintage wins), so a board upgraded from MDT3
 * firmware keeps its tuning. Words 0..6 keep the MDT3 meaning — only the
 * ex-fire-mode bits 31:24 of blanking_us are repurposed for the mode. */
typedef struct __attribute__((aligned(8))) {
    uint32_t magic;                /* 'MDT4'                               */
    uint32_t blanking_us;          /* bits 23:0 blanking; bits 31:24 mode
                                      (0 = all-at-once, 1 = raster)        */
    uint32_t rx_window_us;         /* as MDT3 (rx | samples_per_period<<8) */
    uint32_t coil_spacing_mm;
    int32_t  coil_offset_fore_mm;
    int32_t  coil_offset_right_mm;
    uint32_t tx_pulse_us;
    uint8_t  ch_bl_us[8];          /* raster per-channel table             */
    uint8_t  ch_rx_us[8];
    uint8_t  ch_tx_us[8];
    uint32_t pulse_ticks;          /* requested raster pulse spacing, 0.1 ms
                                      ticks (2..255); pre-pulse records read
                                      erased 0xFFFFFFFF -> default          */
    uint32_t reserved;             /* written erased (0xFFFFFFFF): a future
                                      field reads "not present" in old
                                      records for free, MDT3-style         */
    uint32_t check;                /* ~(XOR of the 15 words above)         */
} md_settings_rec4_t;              /* 64 bytes = 8 flash doublewords       */

_Static_assert(sizeof(md_settings_rec_t)  == 32U, "MDT3 record is 32 bytes");
_Static_assert(sizeof(md_settings_rec4_t) == 64U, "MDT4 record is 64 bytes");

#define MD_SETTINGS_SLOTS  (4096U / sizeof(md_settings_rec_t))
#define MD_SETTINGS_SLOTS4 (4096U / sizeof(md_settings_rec4_t))

static uint32_t md_settings_check_words(const uint32_t *w, uint32_t nwords)
{
    uint32_t x = 0U;
    for (uint32_t i = 0U; i < nwords - 1U; i++)
        x ^= w[i];
    return ~x;
}

static uint32_t md_settings_check(const md_settings_rec_t *r)
{
    return md_settings_check_words((const uint32_t *)r, 8U);
}

static uint32_t md_settings_check4(const md_settings_rec4_t *r)
{
    return md_settings_check_words((const uint32_t *)r, 16U);
}

/* Slot addressing stays in 32-byte units: legacy MDT3 records sit at any
 * 32 B slot, MDT4 records only at even slots (64 B alignment). */
static const md_settings_rec_t *md_settings_slot(uint32_t i)
{
    return (const md_settings_rec_t *)(MD_SETTINGS_PAGE_ADDR
                                       + i * sizeof(md_settings_rec_t));
}

/* A save cut by power loss can leave a doubleword with invalid ECC; any
 * read of it (e.g. the boot-time slot scan) raises an ECC double-error
 * NMI. Without this hook the stock NMI handler hangs forever — a bricked
 * unit. Called from NMI_Handler: if the failing address is inside the
 * settings page, clear the flags, note the fault, and resume (the read
 * returned garbage, which magic/checksum reject); MD_Load_Settings then
 * purges the page. Any other NMI cause returns 0 → original hang. */
static volatile uint32_t md_settings_ecc_fault = 0U;

uint32_t MD_Settings_ECC_NMI(void)
{
    uint32_t eccr = FLASH->ECCR;
    if (!(eccr & (FLASH_ECCR_ECCD | FLASH_ECCR_ECCD2)))
        return 0U;

    /* DBANK=0: ADDR_ECC = byte offset (from flash base) of the failing
     * 128-bit quad word, low 4 bits cleared (RM0440 3.3.2). */
    uint32_t off = eccr & FLASH_ECCR_ADDR_ECC;
    if (off <  (MD_SETTINGS_PAGE_ADDR - FLASH_BASE) ||
        off >= (MD_SETTINGS_PAGE_ADDR - FLASH_BASE) + 4096U)
        return 0U;                     /* ECC fault outside our page       */

    FLASH->ECCR = eccr | FLASH_ECCR_ECCD | FLASH_ECCR_ECCD2;   /* w1c     */
    md_settings_ecc_fault = 1U;
    return 1U;
}

/* Erase the settings page (also the recovery path for ECC faults). */
static void md_settings_erase_page(void)
{
    FLASH_EraseInitTypeDef erase = {
        .TypeErase = FLASH_TYPEERASE_PAGES,
        .Banks     = FLASH_BANK_1,
        .Page      = MD_SETTINGS_PAGE,
        .NbPages   = 1U,
    };
    uint32_t page_err = 0U;
    HAL_FLASH_Unlock();
    __HAL_FLASH_CLEAR_FLAG(FLASH_FLAG_SR_ERRORS);
    (void)HAL_FLASHEx_Erase(&erase, &page_err);
    HAL_FLASH_Lock();
}

void MD_Load_Settings(void)
{
    /* Newest valid record of EITHER vintage wins. Words 0..6 of an MDT4
     * record carry the MDT3 meanings, so `last` reads the shared fields
     * from both; `last4` is non-NULL only when the winner is MDT4. MDT4
     * candidates live at even 32 B slots only (64 B records); a matched
     * one skips the slot holding its second half, whose bytes could
     * otherwise be misread as a record head. */
    const md_settings_rec_t  *last  = NULL;
    const md_settings_rec4_t *last4 = NULL;

    for (uint32_t i = 0U; i < MD_SETTINGS_SLOTS; i++) {
        const md_settings_rec_t *r = md_settings_slot(i);
        if ((i & 1U) == 0U && r->magic == MD_SETTINGS_MAGIC4) {
            const md_settings_rec4_t *r4 = (const md_settings_rec4_t *)r;
            if (r4->check == md_settings_check4(r4)) {
                last  = r;
                last4 = r4;
                i++;                         /* skip the record's tail half  */
            }
            continue;
        }
        if (r->magic == MD_SETTINGS_MAGIC && r->check == md_settings_check(r)) {
            last  = r;                       /* newest valid record wins     */
            last4 = NULL;
        }
    }

    if (md_settings_ecc_fault) {
        /* An interrupted save left invalid ECC somewhere in the page (the
         * scan's NMIs were absorbed above). Purge it and run defaults. */
        md_settings_ecc_fault = 0U;
        md_settings_erase_page();
        last = NULL;
        printf("# settings page had ECC fault -- erased, using defaults\r\n");
    }

    if (last) {
        /* Clamp to the same limits the console enforces (16-bit ARR at
         * 170 MHz ticks) in case the record came from other firmware. */
        uint32_t bl = last->blanking_us & 0x00FFFFFFU;
        md_blanking_us  = (bl <= MD_BLANKING_MAX_US)
                          ? bl : MD_BLANKING_MAX_US;
        uint32_t rxw = last->rx_window_us & 0xFFU;
        uint32_t sp  = (last->rx_window_us >> 8) & 0xFFU;
        md_rx_window_us = (rxw >= 1U && rxw <= MD_RX_WINDOW_MAX_US)
                          ? rxw : MD_RX_WINDOW_US;
        /* 0 = record predates the sample rate; anything not in the step
         * list means foreign firmware — the default applies either way. */
        md_samples_per_period = md_rate_valid(sp)
                          ? (uint8_t)sp : (uint8_t)MD_SAMPLES_PER_GPS_PERIOD;
        /* Older records carry erased 0xFFFFFFFF in this (ex-spare) word —
         * out of range, so the compile-time default applies. */
        md_tx_pulse_us  = (last->tx_pulse_us >= MD_TX_PULSE_MIN_US &&
                           last->tx_pulse_us <= MD_TX_PULSE_MAX_US)
                          ? last->tx_pulse_us : MD_TX_PULSE_US;
        /* Records saved before the geometry fields existed have erased
         * 0xFFFFFFFF in coil_spacing_mm — keep all-default geometry then
         * (the offsets would otherwise read as -1 mm, not 0). */
        if (last->coil_spacing_mm != 0xFFFFFFFFU) {
            md_coil_spacing_mm =
                (last->coil_spacing_mm >= MD_COIL_SPACING_MM_MIN &&
                 last->coil_spacing_mm <= MD_COIL_SPACING_MM_MAX)
                ? last->coil_spacing_mm : MD_COIL_SPACING_MM_DEFAULT;
            md_coil_offset_fore_mm =
                (last->coil_offset_fore_mm  >= -MD_COIL_OFFSET_MM_LIMIT &&
                 last->coil_offset_fore_mm  <=  MD_COIL_OFFSET_MM_LIMIT)
                ? last->coil_offset_fore_mm : 0;
            md_coil_offset_right_mm =
                (last->coil_offset_right_mm >= -MD_COIL_OFFSET_MM_LIMIT &&
                 last->coil_offset_right_mm <=  MD_COIL_OFFSET_MM_LIMIT)
                ? last->coil_offset_right_mm : 0;
        }
        if (last4) {
            /* Per-channel table + mode, each value re-clamped like the
             * shared fields (a foreign record must not arm a slot with an
             * out-of-range timeline). */
            for (uint32_t k = 0U; k < 8U; k++) {
                md_ch_bl_us[k] = (last4->ch_bl_us[k] <= MD_BLANKING_MAX_US)
                                 ? last4->ch_bl_us[k] : (uint8_t)MD_BLANKING_MAX_US;
                md_ch_rx_us[k] = (last4->ch_rx_us[k] >= 1U &&
                                  last4->ch_rx_us[k] <= MD_RX_WINDOW_MAX_US)
                                 ? last4->ch_rx_us[k] : (uint8_t)MD_RX_WINDOW_US;
                md_ch_tx_us[k] = (last4->ch_tx_us[k] >= MD_TX_PULSE_MIN_US &&
                                  last4->ch_tx_us[k] <= MD_TX_PULSE_MAX_US)
                                 ? last4->ch_tx_us[k] : (uint8_t)MD_TX_PULSE_US;
            }
            md_raster = (((last4->blanking_us >> 24) & 0xFFU) == 1U) ? 1U : 0U;
            /* Requested pulse spacing: erased 0xFFFFFFFF in pre-pulse
             * records (and anything out of range) falls back to "as fast
             * as the timings allow". */
            md_pulse_ticks = (last4->pulse_ticks >= MD_SLOT_TICKS_MIN &&
                              last4->pulse_ticks <= 255U)
                             ? (uint8_t)last4->pulse_ticks
                             : (uint8_t)MD_SLOT_TICKS_MIN;
        } else {
            md_table_seed();                 /* legacy record: table = globals */
            md_raster = 0U;
            md_pulse_ticks = MD_SLOT_TICKS_MIN;
        }
        if (md_raster && !md_raster_apply()) {
            /* Foreign/stale combo: sweep doesn't fit the sample interval.
             * Fall back to all-at-once rather than guessing which knob to
             * clamp; the table survives for after a rate change. */
            md_raster = 0U;
            printf("# raster from saved settings does not fit the sample rate -- starting in all mode\r\n");
        } else if (!md_raster) {
            (void)md_raster_apply();         /* best-effort slot period      */
        }
        printf("# settings loaded: blanking=%luus  rx_window=%luus  tx_pulse=%luus  coil_spacing=%lumm  sample_rate=%luHz\r\n",
               md_blanking_us, md_rx_window_us, md_tx_pulse_us, md_coil_spacing_mm,
               md_sample_rate_hz());
    } else {
        /* Nothing valid in flash (new board, or the page was just purged
         * after an ECC fault): persist the compile-time defaults so the
         * unit always carries a valid record. CLEAR re-writes them on demand. */
        md_table_seed();
        (void)md_raster_apply();
        printf("# no saved settings -- writing defaults: blanking=%luus  rx_window=%luus  tx_pulse=%luus  coil_spacing=%lumm  sample_rate=%luHz\r\n",
               md_blanking_us, md_rx_window_us, md_tx_pulse_us, md_coil_spacing_mm,
               md_sample_rate_hz());
        MD_Save_Settings();
    }
}

void MD_Save_Settings(void)
{
    /* Hold the pacer off so no cycle STARTS mid-save (flash ops stall the
     * bus and would defer the timeline's ADC kick). A fire that lands
     * during the save pends and runs right after re-enable. Harmless
     * before md_pace_init (first-boot default write): nothing pends. */
    HAL_NVIC_DisableIRQ(TIM7_DAC_IRQn);

    /* A cycle started just before the disable may still be in flight; the
     * flash stall would defer its ADC kick too, sampling integrators that
     * drooped for the whole operation (~22 ms on a page erase). Wait it
     * out: a full cycle is well under 1 ms, the tick bound is a safety
     * valve. The TIM1/TIM8 UIF terms cover a kick that is pended but not
     * yet taken (TIM8 kicks Set B slots in raster mode). */
    uint32_t t0 = HAL_GetTick();
    while ((((TIM2->CR1 | TIM3->CR1 | TIM1->CR1 | TIM8->CR1) & TIM_CR1_CEN)
            || (TIM1->SR & TIM_SR_UIF) || (TIM8->SR & TIM_SR_UIF)
            || md_adc_done_mask != 0x0FU)
           && (HAL_GetTick() - t0) < 2U) {}

    /* A raster sweep frozen mid-way (its remaining slots pend behind the
     * disabled pacer) resumes with a flash-op-sized hole in its slot
     * spacing — drop the frame instead of publishing one with lying skew.
     * The pacer IRQ is off, so md_sweep_ok is ours to write here. */
    if (md_raster && md_slot != 0U)
        md_sweep_ok = 0U;

    /* First fully-erased 64 B (even-32B-slot-aligned) region; legacy 32 B
     * records occupying half a region make it non-erased, so mixed pages
     * from an MDT3-era board just appear fuller. Page full -> erase. */
    uint32_t slot = MD_SETTINGS_SLOTS;
    for (uint32_t i = 0U; i < MD_SETTINGS_SLOTS && slot == MD_SETTINGS_SLOTS;
         i += 2U) {
        const uint32_t *w = (const uint32_t *)md_settings_slot(i);
        uint32_t j;
        for (j = 0U; j < 16U; j++)
            if (w[j] != 0xFFFFFFFFU)
                break;
        if (j == 16U)
            slot = i;
    }

    md_settings_rec4_t rec;
    memset(&rec, 0xFF, sizeof(rec));
    rec.magic                = MD_SETTINGS_MAGIC4;
    rec.blanking_us          = md_blanking_us
                             | ((uint32_t)(md_raster ? 1U : 0U) << 24);
    rec.rx_window_us         = md_rx_window_us
                             | ((uint32_t)md_samples_per_period << 8);
    rec.tx_pulse_us          = md_tx_pulse_us;
    rec.coil_spacing_mm      = md_coil_spacing_mm;
    rec.coil_offset_fore_mm  = md_coil_offset_fore_mm;
    rec.coil_offset_right_mm = md_coil_offset_right_mm;
    for (uint32_t k = 0U; k < 8U; k++) {
        rec.ch_bl_us[k] = md_ch_bl_us[k];
        rec.ch_rx_us[k] = md_ch_rx_us[k];
        rec.ch_tx_us[k] = md_ch_tx_us[k];
    }
    rec.pulse_ticks          = md_pulse_ticks;
    rec.check                = md_settings_check4(&rec);

    HAL_FLASH_Unlock();

    /* Clear stale SR error flags — notably OPTVERR, which the option-byte
     * loader can leave set at reset; the HAL's entry check would otherwise
     * fail the first program/erase after boot. */
    __HAL_FLASH_CLEAR_FLAG(FLASH_FLAG_SR_ERRORS);

    if (slot == MD_SETTINGS_SLOTS) {
        FLASH_EraseInitTypeDef erase = {
            .TypeErase = FLASH_TYPEERASE_PAGES,
            .Banks     = FLASH_BANK_1,
            .Page      = MD_SETTINGS_PAGE,
            .NbPages   = 1U,
        };
        uint32_t page_err = 0U;
        if (HAL_FLASHEx_Erase(&erase, &page_err) != HAL_OK) {
            HAL_FLASH_Lock();
            HAL_NVIC_EnableIRQ(TIM7_DAC_IRQn);
            printf("# save FAILED: page erase error 0x%08lx\r\n", page_err);
            return;
        }
        slot = 0U;
    }

    HAL_StatusTypeDef st = HAL_OK;
    const uint64_t *src = (const uint64_t *)&rec;
    uint32_t dst = MD_SETTINGS_PAGE_ADDR + slot * sizeof(md_settings_rec_t);
    for (uint32_t i = 0U; i < 8U && st == HAL_OK; i++)
        st = HAL_FLASH_Program(FLASH_TYPEPROGRAM_DOUBLEWORD,
                               dst + 8U * i, src[i]);

    /* HAL_FLASHEx_Erase flushes the ART caches but HAL_FLASH_Program does
     * not: without this, the readback below (and the next save's free-slot
     * scan) can see stale erased 0xFFs from the data cache — the scan would
     * then re-program a written doubleword, which G4 ECC forbids. */
    __HAL_FLASH_DATA_CACHE_DISABLE();
    __HAL_FLASH_DATA_CACHE_RESET();
    __HAL_FLASH_DATA_CACHE_ENABLE();

    HAL_FLASH_Lock();
    HAL_NVIC_EnableIRQ(TIM7_DAC_IRQn);
    md_pace_diag_reset();   /* the ~22 ms hold above is a known, user-made
                               outlier — keep it out of the 'P' statistics */

    const md_settings_rec4_t *r = (const md_settings_rec4_t *)md_settings_slot(slot);
    if (st == HAL_OK && r->magic == MD_SETTINGS_MAGIC4
        && r->check == md_settings_check4(r))
        printf("# saved (slot %lu/%u): blanking=%luus  rx_window=%luus  tx_pulse=%luus  coil_spacing=%lumm  sample_rate=%luHz\r\n",
               slot / 2U, (unsigned)MD_SETTINGS_SLOTS4,
               md_blanking_us, md_rx_window_us, md_tx_pulse_us, md_coil_spacing_mm,
               md_sample_rate_hz());
    else
        printf("# save FAILED: program/verify at slot %lu\r\n", slot / 2U);
}

/* ---------------------------------------------------------------------------
 * 'I' info line: everything the daemon stamps into a study header. One
 * space-separated key=value line, parse-friendly; "?" marks a value the
 * GPS module never reported. Task context only (printf).
 *
 * The identity strings are written by the USART2 ISR (gps_capture_id) and
 * the deferred 'I' path prints on a deadline — i.e. possibly while a late
 * reply is landing — so they are snapshotted with that ISR masked (sub-µs
 * for 128 bytes; a pended char-match is serviced right after, DMA keeps
 * filling). The ISR runs to completion before the task resumes, so the
 * task can never see a half-written string; the mask only makes the
 * snapshot deterministic (a reply landing mid-copy would otherwise read
 * as "?" for that one print). Cheap insurance, not a bug fix.
 *
 * gps_id "none": the module answered $PQTMVERNO but not $PQTMUNIQID on
 * MD_UNIQID_GIVEUP consecutive deferred 'I' replies — it has no unique ID
 * (the boot config already treats the query as optional). Reported as a
 * value so the daemon's header completes and its retry stops; "?" stays
 * the marker for "not heard yet".
 * ------------------------------------------------------------------------- */
#define MD_UNIQID_GIVEUP 2U
static uint8_t md_uniqid_misses = 0U;   /* deferred replies with ver, no id */

void md_print_info(void)
{
    char ver[sizeof gps_version_str];
    char uid[sizeof gps_uniqid_str];
    HAL_NVIC_DisableIRQ(USART2_IRQn);
    memcpy(ver, gps_version_str, sizeof ver);
    memcpy(uid, gps_uniqid_str, sizeof uid);
    HAL_NVIC_EnableIRQ(USART2_IRQn);
    ver[sizeof ver - 1U] = '\0';
    uid[sizeof uid - 1U] = '\0';

    printf("# info fw=%s gps_ver=%s gps_id=%s gps_cfg=%s"
           " blanking_us=%lu rx_window_us=%lu tx_pulse_us=%lu"
           " coil_spacing_mm=%lu coil_offset_fore_mm=%ld coil_offset_right_mm=%ld"
           " sample_rate_hz=%lu adc_oversample=16 adc=PA0,PA1,PA6,PA7,PB1,PB13,PB12,PB14"
           " detector_mode=%s slot_us=%u pulse_us=%u"
           " bl8=%u,%u,%u,%u,%u,%u,%u,%u"
           " rx8=%u,%u,%u,%u,%u,%u,%u,%u"
           " tx8=%u,%u,%u,%u,%u,%u,%u,%u\r\n",
           FW_GIT_HASH,
           ver[0] ? ver : "?",
           uid[0] ? uid : (md_uniqid_misses >= MD_UNIQID_GIVEUP ? "none" : "?"),
           gps_config_state(),   /* boot|resent|pending|noreply|silent — did the
                                    module take its config burst (gps.c) */
           md_blanking_us, md_rx_window_us, md_tx_pulse_us,
           md_coil_spacing_mm,
           (long)md_coil_offset_fore_mm, (long)md_coil_offset_right_mm,
           md_sample_rate_hz(),
           md_raster ? "raster" : "all",
           (unsigned)md_slot_ticks * 100U,
           (unsigned)md_pulse_ticks * 100U,
           md_ch_bl_us[0], md_ch_bl_us[1], md_ch_bl_us[2], md_ch_bl_us[3],
           md_ch_bl_us[4], md_ch_bl_us[5], md_ch_bl_us[6], md_ch_bl_us[7],
           md_ch_rx_us[0], md_ch_rx_us[1], md_ch_rx_us[2], md_ch_rx_us[3],
           md_ch_rx_us[4], md_ch_rx_us[5], md_ch_rx_us[6], md_ch_rx_us[7],
           md_ch_tx_us[0], md_ch_tx_us[1], md_ch_tx_us[2], md_ch_tx_us[3],
           md_ch_tx_us[4], md_ch_tx_us[5], md_ch_tx_us[6], md_ch_tx_us[7]);
}

/* 'P' pacer diagnostics — one '# pace ...' line, then the window resets.
 * ivl_us: the configured sample interval (sweep-to-sweep in raster).
 * fires / skips: cycles (sweeps) started / starts refused by the overlap
 * guard — per slot in raster, so skips can exceed fires there.
 * dev_max_us / jit_max_us: worst |measured - ivl_us| and worst change
 * between consecutive intervals, stamped at the cycle's CEN write — what
 * the coils actually saw. dev_max_us carries a constant floor: the re-arm
 * resets TIM7's counter AFTER the cycle start, so every interval is
 * nominal plus the ISR's own entry-to-arm time (a few µs at -O0 in all
 * mode; ~8x that in raster, one per slot re-arm); it is a true
 * measurement, not jitter. jit_max_us cancels that constant and is the
 * jitter figure. fix_span_us=min/max: valid-GGA-to-GGA spacing
 * at parse end, i.e. the GPS module's own arrival jitter (the pre-2026-09
 * firmware applied exactly this to the pacer as interval stretches).
 * fix_ph_us: where the last GGA fell after a fire (sweeps 0..ivl_us as
 * the free-running pacer and the GPS clock slide past each other; only a
 * refused start leaves it stale enough to read past ivl_us).
 * gps_isr_max_us: longest NMEA parse inside the USART2 ISR. Token names
 * deliberately match none of the daemon's echo patterns (blanking=,
 * tx_pulse=, coil_spacing=, sample_rate=, detector_mode=). */
static void md_print_pace(void)
{
    uint32_t span_min = md_pd_fix_span_min;
    if (span_min == 0xFFFFFFFFU)
        span_min = 0U;
    printf("# pace det=%s ivl_us=%lu fires=%lu skips=%lu dev_max_us=%lu jit_max_us=%lu"
           " fix_n=%lu fix_span_us=%lu/%lu fix_ph_us=%lu gps_isr_max_us=%lu\r\n",
           md_raster ? "raster" : "all",
           md_interval_ticks() * 100U,
           md_pd_fires, md_pd_skips, md_pd_dev_max, md_pd_jit_max,
           md_pd_fix_n, span_min, md_pd_fix_span_max, md_pd_fix_ph,
           md_pd_gps_isr_max);
    md_pace_diag_reset();
}

