/* Force-restore compile-time defaults and persist them (the word-gated
 * CLEAR command — was the single-key 'D'). */
static void md_restore_defaults(void)
{
    /* Mode OFF before the rate write: the pacer IRQ is still live here (it
     * only stops inside MD_Save_Settings), and its sweep-wrap arm computes
     * interval - 7*slot_ticks under the fit invariant that raster mode
     * maintains. An expiry landing between a new (higher) rate and the
     * raster clear would see a shrunken interval with the old slot_ticks
     * and underflow that subtraction (16-bit ARR truncation -> multi-
     * second stall on a GPS-less bench). Raster cleared first, the same
     * expiry just runs one simultaneous cycle at the old cadence. */
    md_raster               = 0U;
    md_sel_ch               = MD_SEL_ALL;
    md_blanking_us          = MD_BLANKING_US;
    md_rx_window_us         = MD_RX_WINDOW_US;
    md_tx_pulse_us          = MD_TX_PULSE_US;
    md_coil_spacing_mm      = MD_COIL_SPACING_MM_DEFAULT;
    md_coil_offset_fore_mm  = 0;
    md_coil_offset_right_mm = MD_COIL_OFFSET_RIGHT_MM_DEFAULT;
    md_samples_per_period   = MD_SAMPLES_PER_GPS_PERIOD;
    md_pulse_ticks          = MD_SLOT_TICKS_MIN;
    md_table_seed();
    (void)md_raster_apply();
    printf("# defaults restored\r\n");
    /* CLEAR is a mode + selection + table change like any other — without
     * this echo the daemon's <key>_current / raster_sel meta (and so the
     * raw view's panel) would keep describing the pre-CLEAR raster state:
     * the saved banner below carries only the legacy global tokens. */
    md_print_rastercfg();
    MD_Save_Settings();
}

/* One keyword-matcher step. Returns 1 if the byte advanced (or restarted)
 * the word — consumed, don't treat it as a key. *pos == len means the full
 * word has been seen; the caller checks the NEXT byte for Enter. */
static int md_word_step(const char *word, uint32_t len, uint32_t *pos,
                        uint8_t ch)
{
    if (*pos < len && ch == (uint8_t)word[*pos]) { (*pos)++; return 1; }
    if (*pos > 0U) {
        *pos = (ch == (uint8_t)word[0]) ? 1U : 0U;
        return (*pos != 0U) ? 1 : 0;
    }
    return 0;
}

/* ---------------------------------------------------------------------------
 * 'I' with the GPS identity still unknown: re-ask the module first, print
 * once both replies have landed or MD_INFO_WAIT_MS has passed. The GPS
 * powers up slightly after the MCU, so the boot-time query in
 * gps_send_config can go unanswered while GGA flows fine; the daemon's 'I'
 * at connect arrives long after the module is up, so asking again there
 * fills the header (2026-09-20). Deferred, never blocking: the frame ring
 * holds MD_FRAME_RING = 32 frames — 64 ms at 500 Hz — so a wait inside the
 * key handler would drop frames. md_info_poll runs from every console
 * poll (task loop, ~1 ms period). A second 'I' while one is pending is
 * folded into it: one answer per outstanding request, within the daemon's
 * 2 s handshake wait either way. Identity known: prints at once, as before.
 * Settled = known, or the module has proven it has no unique ID (version
 * answered, ID not, MD_UNIQID_GIVEUP deferred replies in a row) — then 'I'
 * stops re-asking and reports gps_id=none (see md_print_info).
 * ------------------------------------------------------------------------- */
#define MD_INFO_WAIT_MS 500U
static uint8_t  md_info_pending  = 0U;
static uint32_t md_info_deadline = 0U;

static int md_identity_settled(void)
{
    return gps_identity_known() ||
           (gps_version_str[0] != '\0' && md_uniqid_misses >= MD_UNIQID_GIVEUP);
}

static void md_info_request(void)
{
    if (md_identity_settled()) {
        md_print_info();
        return;
    }
    if (!md_info_pending) {
        gps_query_identity();
        md_info_deadline = HAL_GetTick() + MD_INFO_WAIT_MS;
        md_info_pending  = 1U;
    }
}

static void md_info_poll(void)
{
    if (!md_info_pending)
        return;
    if (gps_identity_known()) {
        md_info_pending = 0U;
        md_print_info();
    } else if ((int32_t)(HAL_GetTick() - md_info_deadline) >= 0) {
        md_info_pending = 0U;
        if (gps_version_str[0] != '\0' && md_uniqid_misses < MD_UNIQID_GIVEUP)
            md_uniqid_misses++;     /* version came, ID did not: strike */
        md_print_info();            /* "?" for whatever the module still owes */
    }
}

/* ---------------------------------------------------------------------------
 * Console: poll USART1 RX from the task loop (detector2 pattern — direct
 * register access, no HAL receive state machine to wedge, no ISR). Drain
 * everything each poll so held keys adjust smoothly; print once.
 *
 * Upper clamps (MD_*_MAX_US) are new on this board — see their definition.
 * ------------------------------------------------------------------------- */
void md_console_poll(void)
{
    USART1->ICR = USART_ICR_ORECF | USART_ICR_FECF
                | USART_ICR_NECF | USART_ICR_PECF;

    int changed = 0;
    int geom_changed = 0;
    int tx_changed = 0;
    int rate_changed = 0;
    int ras_changed = 0;
    int ras_warn = 0;
    /* The warn's operands, SNAPSHOT at the refusal that set ras_warn: a
     * later key in the same drain (a successful apply, a rate change)
     * moves md_slot_want / md_interval_ticks(), and a drain-end print
     * reading them live can pair numbers from two different events —
     * even numbers that satisfy the constraint the warn reports. */
    uint32_t ras_warn_slot = 0U;  /* slot-period operand (ticks)          */
    uint32_t ras_warn_ivl  = 0U;  /* interval operand (ticks) — the
                                     REQUESTED one on a rate refusal      */
    /* Flash writes are word-gated: SAVE+Enter saves, CLEAR+Enter restores
     * defaults and saves. A single stray byte (RX crosstalk from the host's
     * other data line lands as valid-looking key bytes) can never commit to
     * flash. Matcher state is static — words may arrive split across polls.
     * Both matchers step on every byte; a byte neither uses falls through
     * to normal key handling, so tuning keys stay live mid-word. */
    static const char SAVE_WORD[]  = "SAVE";
    static const char CLEAR_WORD[] = "CLEAR";
    static uint32_t save_pos = 0U, clear_pos = 0U;
    while (USART1->ISR & USART_ISR_RXNE) {
        uint8_t ch = (uint8_t)(USART1->RDR & 0xFFU);
        if (save_pos == 4U) {           /* full SAVE seen: want Enter */
            save_pos = 0U;
            if (ch == '\r' || ch == '\n') {
                MD_Save_Settings();
                clear_pos = 0U;
                continue;
            }                           /* not Enter: byte re-enters below */
        }
        if (clear_pos == 5U) {          /* full CLEAR seen: want Enter */
            clear_pos = 0U;
            if (ch == '\r' || ch == '\n') {
                md_restore_defaults();
                save_pos = 0U;
                continue;
            }
        }
        {
            int used = md_word_step(SAVE_WORD,  4U, &save_pos,  ch);
            used    |= md_word_step(CLEAR_WORD, 5U, &clear_pos, ch);
            if (used)
                continue;
        }
        if (ch == 'a' || ch == 'z' || ch == 's' || ch == 'x'
            || ch == 'f' || ch == 'v') {
            if (md_raster) {
                /* Route the edit to the per-channel table (selected channel,
                 * or all 8 in lockstep). An increase that would stretch the
                 * sweep past the sample interval is reverted whole — the
                 * snapshot matters for 'all' edits, where clamped channels
                 * must not walk on a naive undo. */
                int up = (ch == 'a' || ch == 's' || ch == 'f');
                volatile uint8_t *tab;
                uint32_t lo, hi;
                if (ch == 'a' || ch == 'z') {
                    tab = md_ch_bl_us; lo = 0U; hi = MD_BLANKING_MAX_US;
                } else if (ch == 's' || ch == 'x') {
                    tab = md_ch_rx_us; lo = 1U; hi = MD_RX_WINDOW_MAX_US;
                } else {
                    tab = md_ch_tx_us; lo = MD_TX_PULSE_MIN_US; hi = MD_TX_PULSE_MAX_US;
                }
                uint8_t snap[8];
                md_table_copy(snap, tab);
                /* Same bracket + sweep-drop as the h/n path: a 1 µs edit
                 * that crosses a 100 µs tick boundary changes
                 * md_slot_ticks under the pacer's per-slot re-arms —
                 * mixed spacing in one published frame otherwise. Most
                 * edits DON'T move the ticks, so gate the drop on an
                 * actual change (no frame tax per keypress). The adj runs
                 * INSIDE the bracket too: md_start_slot reads the live
                 * table per slot, so a pacer expiry racing the write
                 * could otherwise fire one slot with a refused,
                 * about-to-be-reverted timing that no echo ever reports. */
                HAL_NVIC_DisableIRQ(TIM7_DAC_IRQn);
                if (md_table_adj(tab, up ? 1 : -1, lo, hi)) {
                    uint8_t old_ticks = md_slot_ticks;
                    if (md_raster_apply()) {
                        if (md_slot_ticks != old_ticks && md_slot != 0U) {
                            md_sweep_ok = 0U;
                            /* The slots still to fire re-arm at the new
                             * spacing, so this one sweep interval is off
                             * by (slots fired)*(old-new) — user-made, so
                             * keep it out of the 'P' window like g/b do. */
                            md_pace_diag_reset();
                        }
                        ras_changed = 1;
                    } else {
                        md_table_restore(tab, snap);
                        ras_warn = 1;
                        ras_warn_slot = md_slot_want;
                        ras_warn_ivl  = md_interval_ticks();
                    }
                }
                HAL_NVIC_EnableIRQ(TIM7_DAC_IRQn);
            }
            else if (ch == 'a') { if (md_blanking_us < MD_BLANKING_MAX_US) md_blanking_us += 1U;         changed = 1; }
            else if (ch == 'z') { md_blanking_us  = (md_blanking_us  > 1U) ? md_blanking_us - 1U : 0U;   changed = 1; }
            else if (ch == 's') { if (md_rx_window_us < MD_RX_WINDOW_MAX_US) md_rx_window_us += 1U;      changed = 1; }
            else if (ch == 'x') { md_rx_window_us = (md_rx_window_us > 1U) ? md_rx_window_us - 1U : 1U;  changed = 1; }
            else if (ch == 'f') { if (md_tx_pulse_us < MD_TX_PULSE_MAX_US) md_tx_pulse_us += 1U;         tx_changed = 1; }
            else                { if (md_tx_pulse_us > MD_TX_PULSE_MIN_US) md_tx_pulse_us -= 1U;         tx_changed = 1; }
        }
        else if (ch == 'd') { if (md_coil_spacing_mm < MD_COIL_SPACING_MM_MAX) md_coil_spacing_mm += 10U; geom_changed = 1; }
        else if (ch == 'c') { if (md_coil_spacing_mm > MD_COIL_SPACING_MM_MIN) md_coil_spacing_mm -= 10U; geom_changed = 1; }
        else if (ch == 'g' || ch == 'b') {
            /* Step through the divisor list — the pacer picks the new
             * interval up at its next arm (one transitional interval; the
             * 'P' window is reset so it doesn't read as jitter). In
             * raster mode a step whose interval can't hold the sweep is
             * refused (the echo still confirms the unchanged rate). */
            uint32_t i = 0U;
            while (i < MD_RATE_STEPS - 1U && md_rate_steps[i] != md_samples_per_period)
                i++;
            uint32_t ni = i;
            if (ch == 'g' && i < MD_RATE_STEPS - 1U) ni = i + 1U;
            else if (ch == 'b' && i > 0U) ni = i - 1U;
            if (ni != i && !md_raster_rate_ok(md_rate_steps[ni])) {
                /* The failing pair here is (current slot, REQUESTED
                 * interval) — no apply runs. */
                ras_warn_slot = md_slot_ticks;
                ras_warn_ivl  = MD_GPS_PERIOD_MS * MD_PACE_TICKS_PER_MS
                                / md_rate_steps[ni];
                ras_warn = 1;
            } else {
                md_samples_per_period = md_rate_steps[ni];
                md_pace_diag_reset();
            }
            rate_changed = 1;
        }
        else if (ch == 'h' || ch == 'n') {
            /* Step the requested pulse spacing: 'h' faster (shorter
             * period), 'n' slower. Nearest-in-direction walk so an
             * off-list value from a foreign record still steps sanely.
             * Live in both modes (no lockout): in all mode the apply is
             * a best-effort slot preview — 'r' re-checks the fit anyway. */
            uint8_t cur = md_pulse_ticks, nv = cur;
            if (ch == 'h') {
                for (uint32_t i = MD_PULSE_STEPS; i-- > 0U;)
                    if (md_pulse_steps[i] < cur) { nv = md_pulse_steps[i]; break; }
            } else {
                for (uint32_t i = 0U; i < MD_PULSE_STEPS; i++)
                    if (md_pulse_steps[i] > cur) { nv = md_pulse_steps[i]; break; }
            }
            if (nv != cur) {
                /* The pacer re-reads md_slot_ticks at every per-slot arm,
                 * so an apply landing mid-sweep gives the remaining slots
                 * a different spacing than the fired ones — the frame
                 * would publish with lying skew (the hazard the save path
                 * guards). The IRQ-off bracket makes apply + sweep-drop
                 * atomic against the pacer: without it a sweep START can
                 * slip between a md_slot==0 guard read and the ticks
                 * write and still mix spacings. Sub-µs with IRQs off (a
                 * pended expiry just runs after — 100 µs ticks dwarf it);
                 * the save path holds the same bracket for milliseconds.
                 * Drop only AFTER a successful apply: a refused step
                 * changes nothing, so the in-flight sweep is still good.
                 * The md_slot 0 guard (as in MD_Save_Settings) spares the
                 * slot-7 conversion publishing across the wrap. */
                HAL_NVIC_DisableIRQ(TIM7_DAC_IRQn);
                md_pulse_ticks = nv;
                uint8_t old_ticks = md_slot_ticks;
                if (md_raster_apply()) {
                    if (md_raster && md_slot != 0U) {
                        md_sweep_ok = 0U;
                        if (md_slot_ticks != old_ticks)
                            md_pace_diag_reset();   /* one odd sweep
                                                       interval, user-made */
                    }
                    ras_changed = 1;
                } else if (md_raster) {
                    md_pulse_ticks = cur;  /* sweep wouldn't fit the interval */
                    ras_warn = 1;
                    ras_warn_slot = md_slot_want;
                    ras_warn_ivl  = md_interval_ticks();
                } else {
                    ras_changed = 1;    /* all mode: best-effort, echo anyway */
                }
                HAL_NVIC_EnableIRQ(TIM7_DAC_IRQn);
            } else {
                ras_changed = 1;        /* list end: echo confirms the state */
            }
        }
        else if (ch >= '0' && ch <= '8') {
            md_sel_ch = (uint8_t)(ch - '0');   /* '8' = all channels */
            ras_changed = 1;
        }
        else if (ch == 'r') {
            if (md_raster) {
                /* Back to all-at-once: nothing to restore — the globals were
                 * never touched by raster edits and md_adc_kick reprograms
                 * the pair JSQRs itself. A sweep in flight is abandoned (one
                 * tick gap). */
                md_raster = 0U;
                md_pace_diag_reset();
                ras_changed = 1;
            } else if (md_raster_apply()) {
                md_slot     = 0U;   /* ordered before the mode flag: the pacer
                                       reads slot state only when raster is on */
                md_sweep_ok = 0U;
                md_raster   = 1U;
                md_pace_diag_reset();
                ras_changed = 1;
            } else {
                ras_warn = 1;       /* sweep wouldn't fit the sample interval */
                ras_warn_slot = md_slot_want;
                ras_warn_ivl  = md_interval_ticks();
            }
        }
        else if (ch == 'I') { md_info_request(); }   /* may defer, see above */
        else if (ch == 'P') { md_print_pace(); }
        else if (ch == 'G') {
            gps_passthrough_enabled = !gps_passthrough_enabled;
            printf("# gps passthrough %s\r\n",
                   gps_passthrough_enabled ? "on" : "off");
        }
    }
    if (changed)
        printf("# blanking=%luus  rx_window=%luus\r\n",
               md_blanking_us, md_rx_window_us);
    if (tx_changed)
        printf("# tx_pulse=%luus\r\n", md_tx_pulse_us);
    if (geom_changed)
        printf("# coil_spacing=%lumm\r\n", md_coil_spacing_mm);
    if (rate_changed)
        printf("# sample_rate=%luHz (%u per fix)\r\n",
               md_sample_rate_hz(), md_samples_per_period);
    if (ras_changed)
        md_print_rastercfg();
    if (ras_warn)
        printf("# raster limit: 8 slots of %luus need more than the %luus sample interval -- lower the rate, shrink timings, or speed up the pulse\r\n",
               ras_warn_slot * 100U, ras_warn_ivl * 100U);
    md_info_poll();     /* deferred 'I' reply, after this poll's key echoes */
}

/* Common one-pulse timebase setup: 170 MHz ticks, given end-of-timeline. */
static void md_opm_timebase(TIM_TypeDef *tim, uint32_t arr)
{
    tim->CR1 &= ~TIM_CR1_CEN;
    tim->CR1 |= TIM_CR1_OPM;
    tim->PSC  = 0U;
    tim->ARR  = arr;
    tim->CNT  = 0U;
    tim->EGR  = TIM_EGR_UG;    /* latch PSC now                             */
    tim->SR   = 0U;            /* clear UG-induced UIF and stale flags      */
}

static void md_pace_init(void);   /* TIM7 cycle pacer — defined below */

/* ============================================================================
 * MD_Hardware_Init
 * Called once from the app task after all MX_ inits. Overrides the CubeMX
 * baseline with the hardware-timeline configuration; all pins idle.
 * ========================================================================== */
void MD_Hardware_Init(void)
{
    MD_Load_Settings();   /* apply saved timing before first cycle */

    /* Boot raster-state echo. An MCU reset mid-study reverts RAM state
     * (channel selection to 'all'; mode/tables to the saved record) while
     * the daemon keeps the port — without this line its <key>_current and
     * raster_sel meta would keep describing the pre-reset state, and the
     * raw view would highlight one channel while edits hit all 8. The
     * info line can't carry it: ch= is live UI state, not a header key. */
    md_print_rastercfg();

    const uint32_t tx_arr  = md_tx_pulse_us * MD_TICKS_PER_US;
    const uint32_t aux_arr = (md_tx_pulse_us + md_blanking_us + md_rx_window_us)
                             * MD_TICKS_PER_US;

    /* ---------------- TIM2: master + Set A TX (PA5) ------------------- */
    md_opm_timebase(TIM2, tx_arr);
    TIM2->CR2 = (TIM2->CR2 & ~TIM_CR2_MMS) | TIM_CR2_MMS_0;  /* TRGO = CEN  */
    TIM2->CCR1 = 1U;                       /* TX rise one tick after start  */
    md_oc_mode(TIM2, 1, MD_OCM_FORCE_INACT);
    TIM2->CCER |= TIM_CCER_CC1E;
    TIM2->DIER  = 0U;                      /* no interrupts on TX timers    */

    /* ---------------- TIM3: slave + Set B TX (PB4) -------------------- */
    md_opm_timebase(TIM3, tx_arr);
    md_slave_to_tim2(TIM3);
    TIM3->CCR1 = 1U;
    md_oc_mode(TIM3, 1, MD_OCM_FORCE_INACT);
    TIM3->CCER |= TIM_CCER_CC1E;
    TIM3->DIER  = 0U;

    /* ---------------- TIM1: slave + Set A aux (PA9/PA10/PA11) --------- */
    md_opm_timebase(TIM1, aux_arr);
    md_slave_to_tim2(TIM1);
    md_oc_mode(TIM1, 2, MD_OCM_FORCE_INACT);   /* PA9  LOW  (gain-protect) */
    md_oc_mode(TIM1, 3, MD_OCM_FORCE_INACT);   /* PA10 LOW  (integ reset)  */
    md_oc_mode(TIM1, 4, MD_OCM_FORCE_INACT);   /* PA11 HIGH (RX off, CC4P) */
    TIM1->CCER |= TIM_CCER_CC2E | TIM_CCER_CC3E | TIM_CCER_CC4E | TIM_CCER_CC4P;
    TIM1->CR2  &= ~(TIM_CR2_OIS2 | TIM_CR2_OIS3 | TIM_CR2_OIS4);
    TIM1->BDTR |= TIM_BDTR_MOE | TIM_BDTR_OSSR | TIM_BDTR_OSSI;
    TIM1->DIER  = TIM_DIER_UIE;
    HAL_NVIC_SetPriority(TIM1_UP_TIM16_IRQn, 2, 0);
    HAL_NVIC_EnableIRQ(TIM1_UP_TIM16_IRQn);

    /* ---------------- TIM8: slave + Set B aux (PA15/PB9/PC13) --------- */
    md_opm_timebase(TIM8, aux_arr);
    md_slave_to_tim2(TIM8);
    md_oc_mode(TIM8, 1, MD_OCM_FORCE_INACT);   /* PA15 LOW  (gain-protect) */
    md_oc_mode(TIM8, 3, MD_OCM_FORCE_INACT);   /* PB9  LOW  (integ reset)  */
    md_oc_mode(TIM8, 4, MD_OCM_FORCE_INACT);   /* PC13 HIGH (RX off, CC4NP)*/
    TIM8->CCER |= TIM_CCER_CC1E | TIM_CCER_CC3E | TIM_CCER_CC4NE | TIM_CCER_CC4NP;
    TIM8->CR2  &= ~(TIM_CR2_OIS1 | TIM_CR2_OIS3 | TIM_CR2_OIS4N);
    TIM8->BDTR |= TIM_BDTR_MOE | TIM_BDTR_OSSR | TIM_BDTR_OSSI;
    TIM8->DIER  = TIM_DIER_UIE;
    HAL_NVIC_SetPriority(TIM8_UP_IRQn, 2, 0);
    HAL_NVIC_EnableIRQ(TIM8_UP_IRQn);

    /* ---------------- ADC1..4: injected pairs, all 8 inputs ----------- */
    md_adc_init();

    /* ---------------- ADC5: 1 Hz status (PA8 / temp / VREFINT) -------- */
    md_status_init();

    /* ---------------- TIM7: free-running cycle pacer ------------------- */
    md_pace_init();
}

/* Arm one set for the coming cycle (timers are stopped here, so mode and
 * compare writes are glitch-free). */
static void md_arm_set(md_set_t *s,
                       uint32_t tx_arr, uint32_t aux_ccr, uint32_t aux_arr)
{
    s->tx->ARR  = tx_arr;
    s->opm->ARR = aux_arr;
    md_set_ccr(s->opm, s->gain_ch,  aux_ccr);
    md_set_ccr(s->opm, s->integ_ch, aux_ccr);
    md_set_ccr(s->opm, s->rx_ch,    aux_ccr);

    /* Reset refs LOW first so re-arming can't glitch, then arm. */
    md_oc_mode(s->opm, s->gain_ch,  MD_OCM_FORCE_INACT);
    md_oc_mode(s->opm, s->integ_ch, MD_OCM_FORCE_INACT);
    md_oc_mode(s->opm, s->gain_ch,  MD_OCM_ACT_ON_CMP);  /* latches HIGH      */
    md_oc_mode(s->opm, s->integ_ch, MD_OCM_ACT_ON_CMP);  /* latches HIGH      */
    md_oc_mode(s->opm, s->rx_ch,    MD_OCM_PWM2);        /* hardware window   */

    md_oc_mode(s->tx, 1, MD_OCM_PWM2);   /* coil: rise @1 tick, fall @update */
}

/* ============================================================================
 * md_start_cycle  (called from the TIM7 pacer IRQ — see md_pace_fired)
 * Arms both sets, then starts the master. Every armed timer starts on
 * the same hardware trigger — the only software-timed event is this
 * single CEN write, and nothing downstream depends on when it lands.
 * ========================================================================== */
uint8_t md_start_cycle(void)
{
    if (((TIM2->CR1 | TIM3->CR1 | TIM1->CR1 | TIM8->CR1) & TIM_CR1_CEN)
        || md_adc_done_mask != 0x0FU)
        return 0U;            /* previous cycle (timers or ADC) still running */

    uint32_t tx = md_tx_pulse_us;
    uint32_t bl = md_blanking_us;
    uint32_t rx = md_rx_window_us;
    uint32_t tx_arr  = tx * MD_TICKS_PER_US;
    uint32_t aux_ccr = (tx + bl) * MD_TICKS_PER_US + 1U;
    uint32_t aux_arr = (tx + bl + rx) * MD_TICKS_PER_US;

    md_arm_set(&md_set_a, tx_arr, aux_ccr, aux_arr);
    md_arm_set(&md_set_b, tx_arr, aux_ccr, aux_arr);

    md_cycle_raster = 0U;
    md_ts_cen = dwt_cyccnt();
    TIM2->CR1 |= TIM_CR1_CEN;      /* master + all armed slaves start here   */
    return 1U;
}

/* Park one set for a raster slot it doesn't own: every output forced
 * inactive (coils don't fire, integrators stay reset, RX disconnected —
 * the same refs as the between-cycles idle state). The timers still RUN —
 * they are trigger-slaved to TIM2 and start with it regardless — so they
 * get the slot's ARRs to run out quietly; their UIE is filtered in the
 * handlers below instead of churning DIER per slot. */
static void md_park_set(md_set_t *s, uint32_t tx_arr, uint32_t aux_arr)
{
    s->tx->ARR  = tx_arr;
    s->opm->ARR = aux_arr;
    md_oc_mode(s->tx, 1, MD_OCM_FORCE_INACT);
    md_oc_mode(s->opm, s->gain_ch,  MD_OCM_FORCE_INACT);
    md_oc_mode(s->opm, s->integ_ch, MD_OCM_FORCE_INACT);
    md_oc_mode(s->opm, s->rx_ch,    MD_OCM_FORCE_INACT);
}

/* ============================================================================
 * md_start_slot  (raster mode; called from the TIM7 pacer IRQ)
 * One channel's private cycle: its bus fires with its own {tx, bl, rx},
 * the other bus is parked, and only its ADC channel converts. Same
 * hardware-trigger start and same overlap guard as md_start_cycle.
 * ========================================================================== */
static uint8_t md_start_slot(uint32_t k)
{
    if (((TIM2->CR1 | TIM3->CR1 | TIM1->CR1 | TIM8->CR1) & TIM_CR1_CEN)
        || md_adc_done_mask != 0x0FU)
        return 0U;            /* previous slot (timers or ADC) still running */

    uint32_t tx = md_ch_tx_us[k];
    uint32_t bl = md_ch_bl_us[k];
    uint32_t rx = md_ch_rx_us[k];
    uint32_t tx_arr  = tx * MD_TICKS_PER_US;
    uint32_t aux_ccr = (tx + bl) * MD_TICKS_PER_US + 1U;
    uint32_t aux_arr = (tx + bl + rx) * MD_TICKS_PER_US;

    md_set_t *fire = MD_CH_SET_B(k) ? &md_set_b : &md_set_a;
    md_set_t *idle = MD_CH_SET_B(k) ? &md_set_a : &md_set_b;

    md_arm_set(fire, tx_arr, aux_ccr, aux_arr);
    md_park_set(idle, tx_arr, aux_arr);

    md_slot_ch = (uint8_t)k;       /* settles long before the UIE reads it   */
    md_cycle_raster = 1U;

    md_ts_cen = dwt_cyccnt();
    TIM2->CR1 |= TIM_CR1_CEN;      /* master clock runs every slot; only the
                                      firing set's outputs are armed         */
    return 1U;
}

/* ============================================================================
 * OPM expiry (UIE at end of RX window). Every critical edge this cycle
 * already happened in hardware — the RX disconnect was the PWM2 self-clear
 * at this same update event. All-at-once: TIM1's UIE starts all four ADC
 * sequences. Raster: both aux timers run every slot with the same ARR, so
 * both UIEs fire — only the set that owns the slot's channel kicks.
 * ========================================================================== */
void md_tim1_uie_fired(void)
{
    md_ts_opm = dwt_cyccnt();
    if (!md_cycle_raster)
        md_adc_kick();
    else if (!MD_CH_SET_B(md_slot_ch))
        md_adc_kick_one();
}

void md_tim8_uie_fired(void)
{
    if (md_cycle_raster && MD_CH_SET_B(md_slot_ch))
        md_adc_kick_one();
}

/* ============================================================================
 * Cycle pacing (TIM7, basic timer, one-pulse @ 10 kHz timebase).
 * See metal_detector.h for the cadence contract. The pacer FREE-RUNS: its
 * own expiry ISR is the only place TIM7 is armed (plus md_pace_init's boot
 * arm, before anything can pend), so nothing outside this ISR — not a GPS
 * fix, not the NMEA parser, not the RTOS — can move a coil pulse.
 *
 * History (2026-09-20): until then every valid GGA re-armed TIM7 from the
 * USART2 ISR so a frame completed 1 ms before each fix. That turned the
 * GPS module's sentence-arrival jitter (and the once-per-second GSV block
 * it used to emit) into pulse-interval jitter — post-fix interval anywhere
 * in [I-1 ms, 2I-1 ms) — which the analog chain reads as common-mode
 * noise on every channel (~2k counts per ms of interval change at 200 Hz,
 * bench-measured). Noisy with a lock, quiet with the GPS UART unplugged.
 * The host never needed the lead: it interpolates between anchor ticks,
 * and an anchor's frame completes within one interval before its GGA at
 * any phase. The fix path is now read-only (md_pace_note_fix).
 *
 * NVIC priority 4: above the USART2 GPS parser (6), the GPS DMA IRQ (5)
 * and the FreeRTOS syscall ceiling (5), so none of them can delay an
 * expiry — a delay would be baked into the interval, because the re-arm
 * below resets the counter. Below the timeline ISRs (TIM1/TIM8 UIE at 2,
 * ADC JEOS at 3), which are microseconds long. Consequence: this ISR and
 * everything it calls must never use a FreeRTOS API.
 * ========================================================================== */
static void md_pace_arm_ticks(uint32_t ticks)
{
    /* Floor 2, not 1: ARR gets ticks-1, and a basic timer's counter is
     * BLOCKED while ARR == 0 (RM0440) — a 1-tick arm would park TIM7 dead
     * forever (nothing else ever re-arms it). No caller legitimately
     * wants 1 tick: every path arms at least one slot period (>= 2). */
    if (ticks < 2U)
        ticks = 2U;
    TIM7->CR1 &= ~TIM_CR1_CEN;
    TIM7->ARR  = ticks - 1U;
    TIM7->EGR  = TIM_EGR_UG;   /* latch ARR, reset CNT (URS: no UIF)   */
    /* Belt and braces: OPM stopped the counter at the expiry we are
     * servicing, so no fresh UIF can exist here; but a stale pend costs
     * a doubled fire, so drop both flag and pend anyway. The SR readback
     * orders the flag clear ahead of the pend clear so a still-asserted
     * line can't re-latch (NVIC latches pending on the UIF edge; only
     * exception entry or an ICPR write releases it). */
    TIM7->SR   = 0U;
    (void)TIM7->SR;
    HAL_NVIC_ClearPendingIRQ(TIM7_DAC_IRQn);
    TIM7->CR1 |= TIM_CR1_CEN;
}

static void md_pace_arm(uint32_t ms)
{
    md_pace_arm_ticks(ms * MD_PACE_TICKS_PER_MS);
}

static void md_pace_init(void)
{
    (void)dwt_cyccnt();   /* start the cycle counter the diagnostics stamp */
    md_pace_diag_reset(); /* boot-time GPS traffic (config acks, a saved
                             20 Hz stream) has already stamped the fix
                             side — the first 'P' window starts here */
    __HAL_RCC_TIM7_CLK_ENABLE();
    TIM7->PSC  = (170000U / MD_PACE_TICKS_PER_MS) - 1U;  /* 170 MHz -> 10 kHz */
    /* URS: md_pace_arm's UG reloads PSC/CNT without raising UIF — with
     * UIE live, a UG-induced UIF would pend the IRQ in the NVIC faster
     * than the SR clear can catch it. Only a real expiry interrupts. */
    TIM7->CR1  = TIM_CR1_OPM | TIM_CR1_URS;
    TIM7->DIER = TIM_DIER_UIE;
    /* 4: above USART2 (6), DMA1_Ch1 (5) and the RTOS ceiling (5); below
     * TIM1/TIM8 UIE (2) and ADC (3). See the section comment. */
    HAL_NVIC_SetPriority(TIM7_DAC_IRQn, 4, 0);
    HAL_NVIC_EnableIRQ(TIM7_DAC_IRQn);
    md_pace_arm(1U);   /* first frame right away; the fixed cadence follows */
}

/* Pacer ISR: stamp a started cycle (all mode) or sweep (raster slot 0)
 * and fold its interval into the 'P' statistics. `now` is md_ts_cen, the
 * DWT count at the master timer's CEN write — the coil pulse itself. */
static void md_pace_diag_fire(uint32_t now)
{
    uint32_t prev = md_pd_fire_cyc;
    md_pd_fire_cyc = now;
    md_pd_fires++;
    if (prev == 0U)
        return;                             /* window start: no interval */
    uint32_t ivl = md_cyc_to_us(now - prev);
    uint32_t nom = md_interval_ticks() * 100U;
    uint32_t dev = (ivl > nom) ? ivl - nom : nom - ivl;
    if (dev > md_pd_dev_max)
        md_pd_dev_max = dev;
    uint32_t pi = md_pd_prev_ivl;
    if (pi != 0U) {
        uint32_t jit = (ivl > pi) ? ivl - pi : pi - ivl;
        if (jit > md_pd_jit_max)
            md_pd_jit_max = jit;
    }
    md_pd_prev_ivl = ivl;
}

/* USART2 IRQ context (priority 6). Diagnostics ONLY: reads the fire stamp,
 * never touches TIM7 or any pacer state. A pacer fire preempting the two
 * reads below can skew fix_ph_us for one sample — it steers nothing. */
void md_pace_note_fix(void)
{
    uint32_t fire    = md_pd_fire_cyc;
    uint32_t now     = dwt_cyccnt();
    uint32_t now_ms  = HAL_GetTick();       /* plain volatile read, ISR-safe */
    uint32_t last    = md_pd_fix_cyc;
    uint32_t last_ms = md_pd_fix_ms;
    md_pd_fix_cyc = now;
    md_pd_fix_ms  = now_ms;
    md_pd_fix_n++;
    if (fire != 0U)
        md_pd_fix_ph = md_cyc_to_us(now - fire);
    if (last == 0U)
        return;
    /* > 1 s since the last valid GGA is a dropout, not arrival jitter.
     * Judged on the ms tick, not the cycle count: CYCCNT wraps every
     * 25.27 s, so a 25.5 s or 51 s outage would otherwise read as a
     * sub-second span and pollute min/max. */
    if (now_ms - last_ms > 1000U)
        return;
    uint32_t span = md_cyc_to_us(now - last);
    if (span < md_pd_fix_span_min)
        md_pd_fix_span_min = span;
    if (span > md_pd_fix_span_max)
        md_pd_fix_span_max = span;
}

/* USART2 IRQ context: NMEA parse duration since start_cyc (DWT). The
 * _begin side goes through dwt_cyccnt() so the counter is switched on by
 * the first sentence to arrive, even before md_pace_init — a raw
 * DWT->CYCCNT read with TRCENA clear is architecturally undefined. */
uint32_t md_pace_gps_isr_begin(void)
{
    return dwt_cyccnt();
}

void md_pace_note_gps_isr(uint32_t start_cyc)
{
    uint32_t us = md_cyc_to_us(dwt_cyccnt() - start_cyc);
    if (us > md_pd_gps_isr_max)
        md_pd_gps_isr_max = us;
}

void md_pace_fired(void)
{
    if ((TIM7->SR & TIM_SR_UIF) == 0U)
        return;                     /* not ours (DAC shares the vector) */
    TIM7->SR = 0U;                          /* clear UIF */

    if (!md_raster) {
        /* Every fire consumes a tick, started or not: a skipped slot
         * (previous cycle still in flight — never happens at a 2 ms
         * interval vs ~185 us cycles, but the guard stands) leaves a tick
         * gap instead of quietly relabeling time. The in-flight number is
         * set only on a real start so a frame still converting keeps its
         * own tick. */
        uint32_t tick = md_sample_tick + 1U;
        md_sample_tick = tick;
        if (md_start_cycle()) {
            md_tick_inflight = tick;
            md_pace_diag_fire(md_ts_cen);
        } else {
            md_pd_skips++;
        }
        /* Re-arm at the sample interval, unconditionally and from nowhere
         * else: with or without a GPS fix the stream runs at the
         * configured rate — full rate for bench work with no GPS attached,
         * and the front end keeps its field thermal duty cycle (see the
         * cadence contract in metal_detector.h). */
        md_pace_arm_ticks(md_interval_ticks());
        return;
    }

    /* Raster: one tick per SWEEP (the frame keeps today's cadence and the
     * host's tick math is untouched); the 8 slots ride TIM7 re-arms at the
     * fixed slot period, so value k is measured k*slot_period after the
     * sweep start — the deterministic skew the host corrects for. A slot
     * that finds the previous one still running (budget overrun) kills
     * the sweep: no frame, tick gap, remaining slots skipped (no point
     * heating coils for a frame that won't publish). */
    if (md_slot == 0U) {
        uint32_t tick = md_sample_tick + 1U;
        md_sample_tick = tick;
        md_sweep_ok = md_start_slot(0U);
        if (md_sweep_ok) {
            md_tick_inflight = tick;
            md_pace_diag_fire(md_ts_cen);
        } else {
            md_pd_skips++;
        }
        md_slot = 1U;
        md_pace_arm_ticks(md_slot_ticks);
        return;
    }

    if (md_sweep_ok && !md_start_slot(md_slot)) {
        md_sweep_ok = 0U;
        md_pd_skips++;
    }
    md_slot++;
    if (md_slot < 8U) {
        md_pace_arm_ticks(md_slot_ticks);
        return;
    }

    /* Slot 7 just fired: arm the remainder of the sample interval (the
     * fit check guarantees interval >= 8 slots, so this never underflows
     * below one slot). Sweep-to-sweep spacing is therefore exactly the
     * sample interval, GPS or no GPS. */
    md_slot = 0U;
    md_pace_arm_ticks(md_interval_ticks() - 7U * (uint32_t)md_slot_ticks);
}

/* ============================================================================
 * Injected-sequence completion (JEOS), one per ADC. The last one to land
 * releases gain + integ on both sets: every integrator has been sampled by
 * then.
 * ========================================================================== */
static void md_adc_collect(uint32_t i)
{
    const md_adc_pair_t *p = &md_adc_pairs[i];

    p->adc->ISR = ADC_ISR_JEOS | ADC_ISR_JEOC;          /* clear flags       */

    if (md_kick_raster) {
        /* Raster slot: one conversion, one channel. Release gain+integ on
         * the firing set (the parked set is already forced inactive) and
         * publish the frame only when slot 7 completes a clean sweep. */
        uint32_t k = md_slot_ch;
        md_adc[k] = (uint16_t)p->adc->JDR1;
        md_adc_done_mask = 0x0FU;
        md_set_t *s = MD_CH_SET_B(k) ? &md_set_b : &md_set_a;
        md_oc_mode(s->opm, s->gain_ch,  MD_OCM_FORCE_INACT);
        md_oc_mode(s->opm, s->integ_ch, MD_OCM_FORCE_INACT);
        if (k == 7U && md_sweep_ok) {
            md_cycle_count++;
            uint32_t head = md_frame_head;
            if (head - md_frame_tail < MD_FRAME_RING) {
                md_frame_t *f = &md_frame_ring[head & (MD_FRAME_RING - 1U)];
                f->tick = md_tick_inflight;
                for (uint32_t j = 0U; j < MD_ADC_COUNT; j++)
                    f->adc[j] = md_adc[j];
                md_frame_head = head + 1U;
            } else {
                md_frame_overruns++;
            }
            md_tick_completed = md_tick_inflight;
        }
        return;
    }

    md_adc[p->idx]      = (uint16_t)p->adc->JDR1;
    md_adc[p->idx + 1U] = (uint16_t)p->adc->JDR2;

    uint8_t done = md_adc_done_mask | (uint8_t)(1U << i);
    md_adc_done_mask = done;
    if (done == 0x0FU) {
        md_oc_mode(md_set_a.opm, md_set_a.gain_ch,  MD_OCM_FORCE_INACT);
        md_oc_mode(md_set_a.opm, md_set_a.integ_ch, MD_OCM_FORCE_INACT);
        md_oc_mode(md_set_b.opm, md_set_b.gain_ch,  MD_OCM_FORCE_INACT);
        md_oc_mode(md_set_b.opm, md_set_b.integ_ch, MD_OCM_FORCE_INACT);
        md_cycle_count++;

        /* Frame complete: queue it for the app task's sample line. The
         * head bump publishes after the payload; a full ring drops the
         * frame whole (its tick gap is the host's signal). */
        uint32_t head = md_frame_head;
        if (head - md_frame_tail < MD_FRAME_RING) {
            md_frame_t *f = &md_frame_ring[head & (MD_FRAME_RING - 1U)];
            f->tick = md_tick_inflight;
            for (uint32_t k = 0U; k < MD_ADC_COUNT; k++)
                f->adc[k] = md_adc[k];
            md_frame_head = head + 1U;
        } else {
            md_frame_overruns++;
        }
        md_tick_completed = md_tick_inflight;
    }
}

/* Raw IRQ hooks — called from the handlers in stm32g4xx_it.c USER CODE 1 */
void md_adc12_irq(void)
{
    if (ADC1->ISR & ADC_ISR_JEOS) md_adc_collect(0U);
    if (ADC2->ISR & ADC_ISR_JEOS) md_adc_collect(1U);
}

