#define MD_SLOT_ADC_US    25U   /* one 16x-oversampled conversion is ~23 µs */
#define MD_SLOT_MARGIN_US 5U    /* UIE-to-JADSTART latency + slack          */
#define MD_PACE_TICKS_PER_MS 10U   /* TIM7 timebase: 0.1 ms ticks (10 kHz)  */

