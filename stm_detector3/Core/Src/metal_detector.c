/*
 * metal_detector.c - PI metal detector sequencer (stm_detector3, STM32G474)
 *
 * HARDWARE-TIMELINE ARCHITECTURE (rev 2)
 *
 * All four timers run one shared absolute timeline in one-pulse mode,
 * started by a single hardware trigger. No ISR sits between any two
 * critical edges, so Set A and Set B align to one timer clock (~6 ns)
 * and blanking is exact and identical every cycle.
 *
 *   TIM2  master: TRGO = counter-enable (MMS=Enable). Set A TX on CH1.
 *   TIM3  slave (trigger mode, ITR1 = TIM2_TRGO): Set B TX on CH1.
 *   TIM1  slave (ITR1): Set A aux (CH2 gain / CH3 integ / CH4 RX).
 *   TIM8  slave (ITR1): Set B aux (CH1 gain / CH3 integ / CH4N RX).
 *
 * All PSC=0 → 170 MHz ticks. Timeline (md_start_cycle sets TIM2 CEN;
 * every armed slave starts in the same kernel clock):
 *
 *   t = 1 tick            TX pins HIGH   (PWM2 compare, CCR=1)
 *   t = tx                TX pins LOW    (TX timers' OPM update; they stop)
 *                         (tx = coil charge time, f/v keys 10-120 µs, dfl 120)
 *   t = tx + bl           gain HIGH, integ HIGH, RX pins connect
 *                         (aux compares, one CCR value — same clock, both sets)
 *   t = tx + bl + rx      RX pins disconnect (aux OPM update clears the PWM2
 *                         ref in hardware); TIM1's UIE starts the ADC reads.
 *   + ~45 µs              all four ADCs finish their 2-channel injected
 *                         sequences (16x oversampled — all 8 inputs, every
 *                         cycle); the last JEOS releases gain + integ —
 *                         deliberately non-critical (integrators hold until
 *                         they have been sampled).
 *
 * ADC plan: each ADC converts its own pin pair as a software-started
 * injected sequence (results in JDR1/JDR2 — no DMA). TIM1 runs the
 * timeline; its UIE kicks all four ADCs every cycle and adjacent-coil
 * cross-reads come for free.
 *   ADC1: PA0/PA1 (IN1/IN2)    ADC2: PA6/PA7  (IN3/IN4)
 *   ADC3: PB1/PB13 (IN1/IN5)   ADC4: PB12/PB14 (IN3/IN4)
 *
 * RASTER MODE ('r' key): instead of one simultaneous cycle per sample
 * tick, the pacer runs 8 slots at a fixed slot period (md_slot_ticks x
 * 100 µs, min 200 µs). Slot k fires ONLY channel k's bus with channel k's
 * own {tx, blanking, rx} from the per-channel table, and converts only
 * channel k (single-conversion JSQR, ~23 µs). The idle set's TX and aux
 * outputs are parked Force-Inactive — its coils don't fire and its
 * integrators stay reset. One md_frame_t publishes per completed sweep,
 * so the wire format is unchanged: value k was measured at
 * sweep_start + k*slot_period (the host learns slot_us from the info
 * line). This is the only route to per-channel timing — the gain/integ/RX
 * gates are bussed per set with a single compare value each.
 *
 * TX channels use PWM mode 2 (ref = CNT >= CCR) with CCR = 1 tick: while a
 * timer sits stopped at CNT=0 the ref is LOW, so idle pins are safe — the
 * reason detector2 used force modes instead of plain PWM1. The RX-connect
 * channels use the same trick for a fully hardware 3 µs window: ref rises
 * at the aux compare and falls when the OPM update reloads CNT to 0.
 *
 * Gain/integ channels use Active-on-compare, which latches the ref HIGH
 * through the OPM stop — exactly what the integrator-hold requires.
 *
 * Both coil sets fire every cycle. (Single-set firing — the old 1/2/3
 * "fire mode" keys — was a bring-up diagnostic, removed once all 8
 * coils were validated.)
 *
 * Set A: TX=TIM2 CH1 (PA5), TIM1: CH2=PA9 gain, CH3=PA10 integ,
 *        CH4=PA11 RX connect (CC4P=1 inverts).
 * Set B: TX=TIM3 CH1 (PB4), TIM8: CH1=PA15 gain, CH3=PB9 integ,
 *        CH4N=PC13 RX connect (CC4NP=1 inverts; CC4NE/OIS4N bits).
 *
 * CubeMX still generates a baseline init (PSC=169, TIMING modes); this
 * module owns the final register state, as detector2's MD init did.
 */

