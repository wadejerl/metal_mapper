/* OCxM 3-bit mode values (extended 4th bit always 0 for these modes) */
#define MD_OCM_ACT_ON_CMP    1U   /* OCxREF→1 when CNT=CCRx, latches        */
#define MD_OCM_FORCE_INACT   4U   /* OCxREF=0 immediately                   */
#define MD_OCM_PWM2          7U   /* OCxREF=1 while CNT>=CCRx (self-clears
                                     at OPM update when CNT reloads to 0)   */

/* Write OCxM for channel ch (1..4): CH1/CH3 sit at bits [6:4]+[16] of
 * CCMR1/CCMR2, CH2/CH4 at bits [14:12]+[24]. */
static inline void md_oc_mode(TIM_TypeDef *tim, uint8_t ch, uint32_t mode)
{
    volatile uint32_t *ccmr = (ch <= 2) ? &tim->CCMR1 : &tim->CCMR2;
    uint32_t lo   = (ch & 1U) ? 4U : 12U;
    uint32_t ext  = (ch & 1U) ? 16U : 24U;
    uint32_t mask = (7U << lo) | (1U << ext);
    *ccmr = (*ccmr & ~mask) | (mode << lo);
}

/* CCRx for channel ch (1..4) — consecutive registers */
static inline void md_set_ccr(TIM_TypeDef *tim, uint8_t ch, uint32_t val)
{
    (&tim->CCR1)[ch - 1U] = val;
}

/* Slave a timer to TIM2_TRGO in trigger mode: counter starts in hardware
 * on the master's CEN rising edge. ITR1 = tim2_trgo for TIM1/TIM8
 * (RM0440 Table 267) and TIM3 (Table 291). */
static inline void md_slave_to_tim2(TIM_TypeDef *tim)
{
    tim->SMCR = (tim->SMCR & ~(TIM_SMCR_TS | TIM_SMCR_SMS))
                | TIM_TS_ITR1 | TIM_SLAVEMODE_TRIGGER;
}

