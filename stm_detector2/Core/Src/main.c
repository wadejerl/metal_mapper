/**
 * @brief  Function implementing the defaultTask thread.
 * @param  argument: Not used
 * @retval None
 */
/* USER CODE END Header_StartDefaultTask */
void StartDefaultTask(void *argument)
{
  /* init code for LWIP */
  MX_LWIP_Init();
  /* USER CODE BEGIN 5 */
  printf("# Metal Detector v2 started  blanking=%luus rx_window=%luus\n",
         md_blanking_us, md_rx_window_us);

  // Synchronize GPS read position to current DMA write position
  osDelay(100);
  gps_buffer_read_pos = GPS_DMA_BUFFER_SIZE - __HAL_DMA_GET_COUNTER(huart2.hdmarx);
  last_gga_timestamp = HAL_GetTick();
  printf("# GPS synchronized at DMA position %lu\n", gps_buffer_read_pos);

  uint32_t adc_val = 0;

  for (;;)
  {
    /* --- Keyboard timing adjustment ---
     * a/z: blanking ±2µs    s/x: rx_window ±1µs
     *
     * Read directly from the UART peripheral register instead of using
     * HAL_UART_Receive(timeout=0).  The HAL path can leave RxState=BUSY_RX
     * when no char is available, permanently blocking future calls.  Rapid
     * key-repeat also triggers an overrun error (ORE) that compounds the
     * problem.  Direct register access has no state machine to break.
     *
     * Drain ALL pending bytes each poll so held keys adjust smoothly; print
     * once at the end to avoid spamming the console. */
    {
      extern UART_HandleTypeDef hcom_uart[];
      USART_TypeDef *vcp = hcom_uart[COM1].Instance;

      /* Clear overrun / framing errors before reading */
      vcp->ICR = USART_ICR_ORECF | USART_ICR_FECF | USART_ICR_NECF | USART_ICR_PECF;

      int changed = 0;
      while (vcp->ISR & USART_ISR_RXNE_RXFNE)
      {
        uint8_t ch = (uint8_t)(vcp->RDR & 0xFFU);
        if      (ch == 'a') { md_blanking_us  += 2;                                                changed = 1; }
        else if (ch == 'z') { md_blanking_us   = (md_blanking_us  > 2) ? md_blanking_us  - 2 : 0; changed = 1; }
        else if (ch == 's') { md_rx_window_us += 1;                                                changed = 1; }
        else if (ch == 'x') { md_rx_window_us  = (md_rx_window_us > 1) ? md_rx_window_us - 1 : 1; changed = 1; }
        else if (ch == 'S') { MD_Save_Settings(); }
      }
      if (changed)
        printf("# blanking=%luus  rx_window=%luus\n", md_blanking_us, md_rx_window_us);
    }

    // Consume result from the previous cycle before starting a new one.
    //new_gga_available = true;   // temp for testing (no GPS)
    //latest_gps_position.valid = true;
    md_get_result(&adc_val);

    if (new_gga_available && latest_gps_position.valid)
    {
      printf("%.9f,%.9f,%d,%lu,%.6f\n",
             latest_gps_position.latitude,
             latest_gps_position.longitude,
             latest_gps_position.fix_quality,
             adc_val,
             latest_gps_position.timestamp);

      new_gga_available = 0;
    md_start_cycle();
    }

    // Kick off the next detection cycle (no-op if still running)

    //osDelay(50);
  }
  /* USER CODE END 5 */
}

